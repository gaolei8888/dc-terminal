#!/bin/bash
# dc-workspace 的 PID 1 下面那一层。**它现在起三个东西**：
#
#   dct daemon  —— 会话都挂在它底下，容器活着就是它活着
#   ttyd        —— 把 dct 的终端搬进浏览器，**只绑容器内环回**
#   dct gate    —— 唯一对外的那个端口，只放带对钥匙的人进去（`src/gate.rs`）
#
# 任务 1 那会儿只有一个，是 `exec dct daemon`。
#
# ---------------------------------------------------------------------------
# 为什么 ttyd 绑 127.0.0.1，而不是让门跟它抢同一个端口
# ---------------------------------------------------------------------------
# 门是唯一对外的入口这件事，必须是**网络层面**成立的，不能只是「我们没把那个
# 端口映射出去」。ttyd 绑在容器内环回上之后，同一个 docker 网络里的别的容器
# 也够不着它——只有这个容器里的进程能连，而这个容器里只有门会去连。
#
# `-i 127.0.0.1` 是实测过的：ttyd 的 `--interface` 文档写的是网卡名（eth0），
# 但底下的 libwebsockets 同样收 IP，日志里会打
# `lws_socket_bind: source ads 127.0.0.1`。**别照文档想当然**——我第一版就是
# 想当然地以为它只收网卡名，还把这个误解写进了 Dockerfile 的注释里。
#
# ---------------------------------------------------------------------------
# 为什么 `exec` 没了，换成了 `tini -g`
# ---------------------------------------------------------------------------
# 任务 1 的注释里写着「用 `exec`，好让 SIGTERM 直接落在守护进程身上，中间垫
# 一个 shell 的话信号停在 shell 上」。那句话本身没错，但 `exec` 只能顶替**一个**
# 进程，三个就用不了了。
#
# 换的办法是 Dockerfile 里的 `tini -g`：信号发给子进程**所在的进程组**。
# 凭什么说下面几个进程确实在这个组里——这是这个文件必须回答的那半：
#
#   * bash 跑脚本时**没有作业控制**（非交互、无 job control），后台任务不会被
#     放进各自的进程组，它们跟这个 shell 同组。
#   * 守护进程在这里是 `dct daemon` **直接跑**，不是 `client::spawn_daemon` 拉的。
#     那条路会 `setsid` 另开一个会话（Unix 侧的「脱离终端」），真走那条路的话
#     它就不在这个组里、`-g` 也够不着它了。所以下面那一行必须是 `dct daemon`，
#     不能图省事让 ttyd 里的 `dct` 顺手把守护进程带起来。
#
# 所以 `docker stop` 时 tini 一次把 SIGTERM 发给全部，谁也不用等十秒超时。
#
# ---------------------------------------------------------------------------
# 但别把这里发生的事说大了（2026-09-06 实测，退出码 143 = 128+15）
# ---------------------------------------------------------------------------
# `daemon.rs` 里**没有** SIGTERM 处理器——`sys::signal` 那一套是给 TUI 还原
# 终端用的，守护进程一次都没调过。所以它是被 SIGTERM 的默认动作直接打死的，
# 并没有「自己把 pty 收拾干净」。agent 照样会被清掉，但那是**内核**关掉 pty
# 主端之后发的 SIGHUP（`sys::job` 模块头描述的正是这条 Unix 路径），是内核的
# 功劳不是 dct 的。
#
# 差别是实打实的：没有 `PtySession::kill` 里那 200ms 宽限期，agent 没机会自己
# 收尾落盘。要补的话是在 `daemon.rs` 装一个 SIGTERM 处理器走正常停机路径——
# 那是 dct 的改动，不是这个文件的，也不在第一期。
#
# tini 仍然在前面，因为信号只是它一半的活：另一半是收尸——父进程先死时孤儿会
# 被 reparent 到 PID 1，不 reap 的 PID 1 会让僵尸堆到进程表满。守护进程自己
# `child.wait()` 收得干净（`pty.rs` 那条 `no_zombie` 测试盯着），它管不到的是
# 别人留下的孤儿。**这一条还没在容器里实测**，任务 2 的验收条件就是验它。

# 没有 `-e`：下面要靠 `wait -n` 的返回码判断是谁先死的，`-e` 会抢在那之前
# 把脚本打断，于是永远走不到「把别的也带走」那一步。
set -uo pipefail

PORT="${DCW_PORT:-7681}"
TTYD_PORT="${DCW_TTYD_PORT:-7682}"
SOCK="$HOME/.dct/daemon.sock"

dct daemon &
daemon_pid=$!

# 等 socket 出现再起 ttyd。理由不是好看：不带参数的 `dct` 连不上守护进程时会
# **自己拉一个**（`client::spawn_daemon`）。浏览器要是刚好在这个空档里连进来，
# 容器里就会有两个守护进程去抢同一个 socket 路径。
#
# 最多等 5 秒，等不到也照样起 ttyd——那时候界面上会如实报「连不上」，比在这里
# 静悄悄地卡住强：卡住的话学生看到的是一个永远转圈的页面，没有任何一句话。
for _ in $(seq 50); do
  [ -S "$SOCK" ] && break
  sleep 0.1
done

# `-W`：**ttyd 1.7 起默认是只读的**，不给这个参数，页面出得来、键盘全不管用。
# `-t disableLeaveAlert=true`：关掉浏览器自带的「确定要离开吗」。那句话在别的
#   网页终端上是对的，在这里是反的——这个产品的承诺就是「关掉浏览器，会话照
#   跑」，弹一句暗示「你要丢东西了」等于当面拆自己的台。
# `-m 8`：**这不是一道门**（门是下面那个进程）。它挡的是「页面卡了就狂刷新」
#   ——每刷一次就是一个新的 TUI 进程，不封顶的话一个人能把自己那 2 GB 刷满。
# `--index` 指的是构建时拼好的那一页：ttyd 自己的前端，加上右边那条上传栏
# （Dockerfile 里 `upload-panel.html` 那一步）。**上传本身由 `dct gate` 接**，
# ttyd 只是把那段界面发出去——它对上传这件事一无所知。
#
# `-T xterm-256color` 是 ttyd 的默认值，写出来是因为它跟 Dockerfile 里那个
#   `ENV TERM` 必须是同一个值：守护进程从 ENV 拿 TERM，这条连接从 ttyd 拿，
#   两处报的不是一回事的话，会话里的画面和界面就对不上。
#
# 一个会让人白查半天的现象，先写在这里：起来之后 `ps` 看 ttyd 的命令行，
# `disableLeaveAlert=true` 里那个 `=` 不见了，显示成两个参数。那不是这里写错
# 了——是 ttyd 自己在原地把 `=` 改写成 `\0` 来切 key/value，改的正是 argv
# 那块内存，于是 `/proc/<pid>/cmdline` 跟着变。参数是对的。
#
# 跑的是裸 `dct`，不是 `bash -lc dct`：少一层进程，而且退出看板就等于这条连接
# 结束（ttyd 按 `-s` 的默认值给子进程发 SIGHUP），页面会如实显示断开。刷新一下
# 就是一个新的 TUI 接回同一个守护进程——那正是「关掉浏览器会话照跑」的同一条路。
ttyd \
  --interface 127.0.0.1 \
  --port "$TTYD_PORT" \
  --writable \
  --max-clients 8 \
  --terminal-type xterm-256color \
  --client-option disableLeaveAlert=true \
  --index /usr/local/share/dcw/index.html \
  dct &
ttyd_pid=$!

# 那道门。**它是这个容器里唯一绑 0.0.0.0 的进程**，前面就是宿主的端口映射。
#
# `--bind 0.0.0.0` 必须显式写：`dct gate` 默认只绑环回，因为它自己不加密，
# 默认值得是那个错了也不出事的（见 `gate.rs` 里 `GateArgs::bind`）。这里写出来
# 是因为容器里那句话成立——外面还有宿主的端口映射和（该有的）反代拦着。
#
# `--url`：外面看到的地址。容器不知道自己被映射到哪儿，所以只能由起它的人
# 告诉它（`DCW_PUBLIC_URL`）。不给的话门会印一条按容器网桥地址猜的链接，
# 并且明说那是猜的。
gate_args=(--bind 0.0.0.0 --port "$PORT" --upstream "127.0.0.1:$TTYD_PORT")
[ -n "${DCW_PUBLIC_URL:-}" ] && gate_args+=(--url "$DCW_PUBLIC_URL")
dct gate "${gate_args[@]}" &
gate_pid=$!

# 谁先死，容器就跟着结束。**不能只 wait 守护进程**：ttyd 或者门悄悄挂掉的话
# 容器还「健康」着，学生打不开页面，而 `docker ps` 说一切正常——那是最难查的
# 一种坏法。
wait -n
status=$?
kill -TERM "$daemon_pid" "$ttyd_pid" "$gate_pid" 2>/dev/null
wait
exit "$status"
